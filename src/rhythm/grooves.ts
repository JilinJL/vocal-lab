export const METER_SPECS: Record<MeterId, MeterSpec> = {
  '4/4': { id: '4/4', label: '4/4 强-弱-次强-弱', beats: 4, grooveSub: 4, pulse: [3, 1, 2, 1] },
  '3/4': { id: '3/4', label: '3/4 强-弱-弱', beats: 3, grooveSub: 4, pulse: [3, 1, 1] },
  '2/4': { id: '2/4', label: '2/4 强-弱', beats: 2, grooveSub: 4, pulse: [3, 1] },
  '6/8': { id: '6/8', label: '6/8 强-弱-弱-次强-弱-弱', beats: 6, grooveSub: 2, pulse: [3, 1, 1, 2, 1, 1] },
}

export function getMeterSpec(meter: MeterId): MeterSpec {
  return METER_SPECS[meter] ?? METER_SPECS['4/4']
}

export function getGrooveCellCount(meter: MeterId): number {
  const spec = getMeterSpec(meter)
  return spec.beats * spec.grooveSub
}

export function parseVelocityString(meter: MeterId, encoded: string): VelocityLevel[] {
  const count = getGrooveCellCount(meter)
  const out: VelocityLevel[] = new Array<VelocityLevel>(count).fill(0)
  for (let i = 0; i < Math.min(encoded.length, count); i++) {
    const num = Number.parseInt(encoded[i] ?? '0', 10)
    if (num === 1 || num === 2 || num === 3) {
      out[i] = num
    }
  }
  return out
}

export function grooveToPatternData(preset: GroovePreset): GroovePatternData {
  return {
    kick: parseVelocityString(preset.meter, preset.kick),
    snare: parseVelocityString(preset.meter, preset.snare),
    hat: parseVelocityString(preset.meter, preset.hat),
    fill: parseVelocityString(preset.meter, preset.fill),
  }
}

export function computeSwingOffsetSec(
  pos: number,
  subdivision: number,
  bpm: number,
  swing: number,
): number {
  if (swing <= 0.5001) return 0
  if (subdivision !== 4) return 0
  if (pos % 4 !== 2) return 0
  return (swing - 0.5) * (60 / bpm)
}

